"""Generate or check frontend wire types from local OpenAPI; never starts a server."""

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend"))


def typescript(schema):
    if "$ref" in schema:
        return f"ApiSchemas[{json.dumps(schema['$ref'].rsplit('/', 1)[-1])}]"
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    for key in ("anyOf", "oneOf"):
        if key in schema:
            return " | ".join(typescript(part) for part in schema[key])
    if "allOf" in schema:
        return " & ".join(typescript(part) for part in schema["allOf"])
    kind = schema.get("type")
    if kind in ("integer", "number"):
        return "number"
    if kind in ("string", "boolean", "null"):
        return kind
    if kind == "array":
        return f"Array<{typescript(schema.get('items', {}))}>"
    if kind == "object" or "properties" in schema:
        required = schema.get("required", [])
        fields = [
            f"{json.dumps(name)}{'' if name in required else '?'}: {typescript(value)};"
            for name, value in schema.get("properties", {}).items()
        ]
        additional = schema.get("additionalProperties")
        if additional is not False and not fields:
            return f"Record<string, {typescript(additional) if isinstance(additional, dict) else 'unknown'}>"
        if isinstance(additional, dict):
            fields.append(f"[key: string]: {typescript(additional)};")
        return "{ " + " ".join(fields) + " }"
    return "unknown"


def main():
    from app.config import Settings
    from app.main import create_app

    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    application = create_app(Settings(DATABASE_URL="sqlite+aiosqlite:///:memory:"))
    schemas = application.openapi()["components"]["schemas"]
    output = "// Generated by scripts/contracts.py. Do not edit by hand.\nexport interface ApiSchemas {\n"
    output += "\n".join(
        f"  {json.dumps(name)}: {typescript(schema)};"
        for name, schema in sorted(schemas.items())
    )
    output += "\n}\n"
    path = ROOT / "frontend/src/contracts/api.generated.ts"
    if args.check:
        if not path.exists() or path.read_text() != output:
            raise SystemExit(
                "Wire contracts changed. Run: uv run --project backend python scripts/contracts.py"
            )
        print("OpenAPI wire contracts match generated frontend types.")
    else:
        path.write_text(output)
        print(f"Generated {len(schemas)} local API schemas.")


if __name__ == "__main__":
    main()
